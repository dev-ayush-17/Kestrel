"use client";

import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean }
>(({ className, hoverable = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-lg border border-brand-border bg-brand-surface text-brand-ink transition-all duration-200",
      hoverable && "hover:border-brand-border-dark hover:shadow-xs",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

